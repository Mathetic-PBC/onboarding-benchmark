import os, sys, collections
sys.path.insert(0, os.path.dirname(__file__))
from bm import Manifest, copy, mtime
H = os.path.expanduser('~')
notes = Manifest('authentic', 'local-notes')
files = Manifest('authentic', 'local-files')
NOTE_EXT = {'md', 'markdown', 'txt', 'docx', 'doc', 'html', 'htm', 'rtf', 'pages', 'odt'}
SKIP_EXT = {'dmg', 'pkg', 'exe', 'pyc', 'ds_store', 'localized'}
SKIP_PREFIX = ('Documents/mathetic/', 'Documents/Obsidian Vault/', 'Documents/Zoom/')
skipped = collections.Counter()
for line in open(sys.argv[1]):
    rel = line.rstrip('\n')
    base = os.path.basename(rel)
    ext = base.rsplit('.', 1)[-1].lower() if '.' in base else ''
    if rel.startswith(SKIP_PREFIX) or ext == 'pdf':
        continue  # already collected under obsidian / zoom / pdfs
    if ext in SKIP_EXT or base == '.DS_Store':
        skipped[ext or base] += 1; continue
    src = os.path.join(H, rel)
    if not os.path.isfile(src): continue
    loc = rel.replace('Library/Mobile Documents/com~apple~CloudDocs', 'iCloud Drive')
    top = loc.split('/')[0]
    n = []
    parts = loc.split('/')
    if len(parts) > 2 and parts[0] == 'Downloads' and any(k in parts[1] for k in ['human-compact', 'compact-focus', 'nextjs', 'design_handoff', 'vault']):
        n.append('inside an unpacked software/plugin bundle in Downloads')
    if loc.startswith(('Desktop/paper/', 'Downloads/paper/')):
        n.append('HARD CASE: near-duplicate analysis-code folder (Desktop/paper vs Downloads/paper)')
    if loc.startswith('Projects/engelbart-release-reports/'):
        n.append('release report generated by tooling')
    m = notes if ext in NOTE_EXT else files
    dest = os.path.join(m.dir, loc)
    copy(src, dest)
    m.add(loc, 'Local files on this Mac', top, mtime(src), source='~/' + rel, notes='; '.join(n))
print('notes', notes.save(), 'files', files.save(), 'skipped', dict(skipped))
