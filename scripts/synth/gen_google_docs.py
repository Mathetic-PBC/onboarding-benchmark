def P(acct, path, shared=False):
    return f'{acct}/{"shared-with-me" if shared else "my-drive"}/{path}'


def fix_office(data, modified):
    """openpyxl stamps dcterms:modified with the save time and python-docx/pptx leave a 'generated by' description:
    rewrite docProps/core.xml so the document's own modified date matches the file time."""
    import re, zipfile
    mod = dt(modified).astimezone(UTC).strftime('%Y-%m-%dT%H:%M:%SZ')
    zin = zipfile.ZipFile(io.BytesIO(data)); out = io.BytesIO()
    with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as zout:
        for it in zin.infolist():
            b = zin.read(it.filename)
            if it.filename == 'docProps/core.xml':
                x = b.decode()
                x = re.sub(r'(<dcterms:modified[^>]*>)[^<]*(</dcterms:modified>)', lambda m_: m_.group(1) + mod + m_.group(2), x)
                x = re.sub(r'<dc:description>generated[^<]*</dc:description>', '<dc:description/>', x)
                b = x.encode()
            zi = zipfile.ZipInfo(it.filename, date_time=dt(modified).timetuple()[:6])  # no save-time leak, deterministic
            zi.compress_type = zipfile.ZIP_DEFLATED; zi.external_attr = it.external_attr
            zout.writestr(zi, b)
    return out.getvalue()


def _office(kind, acct, path, content, c, m, pids, notes, shared, author, title):
    rel = P(acct, path, shared)
    t = title or os.path.splitext(os.path.basename(path))[0]
    fn = {'docx': docx_bytes, 'xlsx': xlsx_bytes, 'pptx': pptx_bytes}[kind]
    mo = MOD_SHARED if shared else {'docx': MOD_DOC, 'xlsx': MOD_SHEET, 'pptx': MOD_SLIDES}[kind]
    g.bytes(rel, fix_office(fn(content, t, author, c, m), m), c, m, account=acct, project_ids=pids, modeled_on=mo, notes=notes)


def doc(acct, path, blocks, c, m, pids, notes='', shared=False, author='David Barron', title=None):
    _office('docx', acct, path, blocks, c, m, pids, notes, shared, author, title)


def sheet(acct, path, tabs, c, m, pids, notes='', shared=False, author='David Barron'):
    _office('xlsx', acct, path, tabs, c, m, pids, notes, shared, author, None)


def slides(acct, path, sl, c, m, pids, notes='', shared=False, author='David Barron'):
    _office('pptx', acct, path, sl, c, m, pids, notes, shared, author, None)


