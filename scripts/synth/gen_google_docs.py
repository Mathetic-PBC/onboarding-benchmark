def diagram_png(title, boxes, arrows, size=(900, 420), bars=None):
    """boxes: [(x, y, w, h, label)], arrows: [(i, j)] between box centres; bars: [(label, value)] draws a bar chart instead."""
    from PIL import Image, ImageDraw, ImageFont
    im = Image.new('RGB', size, 'white'); d = ImageDraw.Draw(im)
    try:
        f = ImageFont.load_default(size=18); ft = ImageFont.load_default(size=22)
    except TypeError:
        f = ft = ImageFont.load_default()
    d.text((20, 12), title, fill='black', font=ft)
    if bars:
        mx = max(v for _, v in bars); bw = (size[0] - 120) // len(bars)
        for i, (lab, v) in enumerate(bars):
            x0 = 80 + i * bw; h = int((size[1] - 120) * v / mx)
            d.rectangle([x0 + 10, size[1] - 50 - h, x0 + bw - 10, size[1] - 50], fill=(70, 110, 180))
            d.text((x0 + 12, size[1] - 44), lab, fill='black', font=f)
            d.text((x0 + 12, size[1] - 72 - h), f'{v}', fill='black', font=f)
    for x, y, w, h, lab in boxes:
        d.rounded_rectangle([x, y, x + w, y + h], radius=10, outline=(40, 40, 40), width=2, fill=(235, 242, 252))
        d.multiline_text((x + 10, y + 10), lab, fill='black', font=f, spacing=4)
    for i, j in arrows:
        a, b = boxes[i], boxes[j]
        x1, y1 = a[0] + a[2], a[1] + a[3] // 2; x2, y2 = b[0], b[1] + b[3] // 2
        d.line([x1, y1, x2, y2], fill=(40, 40, 40), width=3)
        d.polygon([(x2, y2), (x2 - 12, y2 - 7), (x2 - 12, y2 + 7)], fill=(40, 40, 40))
    out = io.BytesIO(); im.save(out, 'PNG'); return out.getvalue()


